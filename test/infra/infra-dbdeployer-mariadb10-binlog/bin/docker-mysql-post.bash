#!/bin/bash
set -e
set -o pipefail
[ -f .env ] && . .env

CONTAINER="${COMPOSE_PROJECT}-dbdeployer1-1"

# Prepare cert bundle directories
BUNDLE_DIR="${INFRA_LOGS_PATH}/${INFRA_ID}/proxysql"
sudo mkdir -p "${BUNDLE_DIR}"
sudo chmod 777 "${BUNDLE_DIR}"

DB_BUNDLE="${BUNDLE_DIR}/dbservers-cert-bundle.pem"
CA_BUNDLE="${BUNDLE_DIR}/caservers-cert-bundle.pem"
sudo rm -f "${DB_BUNDLE}" "${CA_BUNDLE}"

# Verify all 3 MariaDB nodes are reachable
for PORT in 3306 3307 3308; do
    echo -n "Verifying MariaDB on ${CONTAINER}:${PORT}..."
    MAX_WAIT=60
    COUNT=0
    while ! docker exec "${CONTAINER}" mysql -h127.0.0.1 -P${PORT} -uroot -p"${ROOT_PASSWORD}" -e "SELECT 1" >/dev/null 2>&1; do
        if [ $COUNT -ge $MAX_WAIT ]; then
            echo " TIMEOUT"
            exit 1
        fi
        echo -n "."
        sleep 2
        COUNT=$((COUNT + 2))
    done
    echo " OK"
done

# Verify TLS is actually enabled. dbdeployer does not create certs for MariaDB
# sandboxes, so the entrypoint generates them; this asserts the nodes really
# picked them up. Without this, a reader started with --ssl-mode=REQUIRED would
# fail later with a confusing connector error instead of a clear infra failure.
for PORT in 3306 3307 3308; do
    HAVE_SSL=$(docker exec "${CONTAINER}" mysql -h127.0.0.1 -P${PORT} -uroot -p"${ROOT_PASSWORD}" -N -B \
        -e "SHOW VARIABLES LIKE 'have_ssl';" 2>/dev/null | awk '{print $2}')
    if [ "${HAVE_SSL}" = "YES" ]; then
        echo "MariaDB ${PORT}: TLS enabled"
    else
        echo "ERROR: MariaDB ${PORT} reports have_ssl='${HAVE_SSL}', expected YES"
        exit 1
    fi
done

# The servers keep MariaDB's stock session-tracking defaults, which do not
# include 'last_gtid'. Reporting each session's own GTID in the OK packet is
# ProxySQL's job: with mysql-default_session_track_gtids=OWN_GTID it adds
# 'last_gtid' to every backend connection's session_track_system_variables.
# Enabling it globally here would hide a broken ProxySQL path (issue #6331).

# Verify replication is working on nodes 2 and 3.
# MariaDB reports this through SHOW SLAVE STATUS (it has no Replica_*_Running
# column names, though it does accept SHOW REPLICA STATUS as an alias).
for PORT in 3307 3308; do
    echo -n "Checking replication on port ${PORT}..."
    SLAVE_STATUS=$(docker exec "${CONTAINER}" mysql -h127.0.0.1 -P${PORT} -uroot -p"${ROOT_PASSWORD}" -E -e "SHOW SLAVE STATUS" 2>/dev/null)
    IO_RUNNING=$(echo "${SLAVE_STATUS}" | grep "Slave_IO_Running:" | awk '{print $2}')
    SQL_RUNNING=$(echo "${SLAVE_STATUS}" | grep "Slave_SQL_Running:" | awk '{print $2}')
    if [ "${IO_RUNNING}" = "Yes" ] && [ "${SQL_RUNNING}" = "Yes" ]; then
        echo " OK (IO: Yes, SQL: Yes)"
    else
        echo " WARNING (IO: ${IO_RUNNING}, SQL: ${SQL_RUNNING})"
    fi
done

# Publish the CA that signed the nodes' certificates.
#
# The MySQL binlog infras collect per-node ca.pem files because dbdeployer
# generates a separate CA per node. Here there is a single CA generated by the
# entrypoint and shared by all three nodes, so one file suffices.
echo "Collecting the infra CA certificate..."
if docker exec "${CONTAINER}" test -f /etc/mysql-tls/ca.pem; then
    docker exec "${CONTAINER}" cat /etc/mysql-tls/ca.pem \
        | sudo tee "${DB_BUNDLE}" > /dev/null
    sudo cp "${DB_BUNDLE}" "${CA_BUNDLE}"
    sudo chmod 666 "${DB_BUNDLE}" "${CA_BUNDLE}"
    echo "  CA written to ${CA_BUNDLE}"
else
    echo ">>> CA not found at /etc/mysql-tls/ca.pem. Skipping."
fi

echo "docker-mysql-post.bash complete."
